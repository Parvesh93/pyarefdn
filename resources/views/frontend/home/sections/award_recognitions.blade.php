<script>
  (function () {
    const sections = [...document.querySelectorAll('section[id^="y"]')];
    const links = [...document.querySelectorAll('aside nav a')];
    const byId = id => links.find(a => a.getAttribute('href') === '#' + id);

    // highlight first by default
    if (links[0]) links[0].classList.add('bg-gray-100','text-amber-600','font-semibold');

    const obs = new IntersectionObserver((entries) => {
      entries.forEach(e => {
        if (e.isIntersecting) {
          links.forEach(a => a.classList.remove('bg-gray-100','text-amber-600','font-semibold'));
          const active = byId(e.target.id);
          if (active) active.classList.add('bg-gray-100','text-amber-600','font-semibold');
        }
      });
    }, { rootMargin: '-40% 0px -55% 0px', threshold: 0 });

    sections.forEach(s => obs.observe(s));
  })();
</script>
